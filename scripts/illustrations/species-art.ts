// Círculos como um único path: [[cx, cy, r], ...]
function dots(list: [number, number, number][]) {
  return list
    .map(
      ([x, y, r]) =>
        `M${x - r} ${y}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`
    )
    .join('')
}

// Cauda bifurcada genérica a partir da base do pedúnculo.
function forkedTail(x: number, top: number, bottom: number, depth = 38) {
  const mid = (top + bottom) / 2
  const tip = x - depth
  return `M${x} ${top}C${x - 10} ${top - 5} ${tip + 12} ${mid - 20} ${tip} ${mid - 30}C${tip + 6} ${mid - 16} ${tip + 10} ${mid - 6} ${tip + 13} ${mid}C${tip + 10} ${mid + 6} ${tip + 6} ${mid + 16} ${tip} ${mid + 30}C${tip + 12} ${mid + 20} ${x - 10} ${bottom + 5} ${x} ${bottom}Z`
}

